import React, { useState } from 'react';
import { ReportCard as ReportCardType } from '../types';
import { 
  Crosshair, 
  Droplets, 
  Compass, 
  Mountain, 
  Sun, 
  Radio, 
  Send, 
  Download, 
  Check, 
  Info,
  Waves
} from 'lucide-react';

interface ReportCardProps {
  data: ReportCardType | null;
  onFlyToSite: (lat: number, lon: number) => void;
}

export const ReportCard: React.FC<ReportCardProps> = ({ data, onFlyToSite }) => {
  const [copied, setCopied] = useState(false);

  if (!data) {
    return (
      <div className="hud-panel rounded-lg p-6 text-center text-slate-400 font-mono text-xs tactical-corners flex flex-col items-center justify-center min-h-[320px]">
        <Crosshair className="w-8 h-8 text-mars-red-bright/60 mb-3 animate-pulse" />
        <p className="font-semibold text-slate-300 uppercase tracking-wider mb-1">
          AWAITING TARGET COORDINATES
        </p>
        <p className="text-slate-500 max-w-[260px]">
          Click anywhere on the Mars 3D globe or select a site from the recommendations to inspect suitability.
        </p>
      </div>
    );
  }

  const confidenceBadgeStyles: Record<string, string> = {
    HIGH: 'bg-emerald-950/80 text-emerald-400 border-emerald-500/50 shadow-[0_0_10px_rgba(16,185,129,0.3)]',
    MEDIUM: 'bg-amber-950/80 text-amber-400 border-amber-500/50 shadow-[0_0_10px_rgba(245,158,11,0.3)]',
    LOW: 'bg-rose-950/80 text-rose-400 border-rose-500/50 shadow-[0_0_10px_rgba(244,63,94,0.3)]',
  };

  const confidence = (data.confidence_level || 'MEDIUM').toUpperCase();
  const badgeClass = confidenceBadgeStyles[confidence] || confidenceBadgeStyles.MEDIUM;
  const scorePct = Math.round((data.suitability_score ?? 0.5) * 100);
  const iceDepth = typeof data.ice_depth_m === 'number' ? data.ice_depth_m : 2.1;
  const iceStd = typeof data.ice_depth_std_m === 'number' ? data.ice_depth_std_m : 1.8;
  const metrics = data.metrics || {
    ice_score: 0.85,
    safety_score: 0.85,
    power_score: 0.80,
    radiation_score: 0.80,
    elevation_m: -3900,
    slope_deg: 1.2,
  };

  const handleExport = () => {
    const reportText = `=== AREOSITE MISSION PLANNER REPORT CARD ===
Site: ${data.site_name || 'Martian Site'} (${data.coordinates_formatted || 'Coordinates'})
Suitability Score: ${scorePct}%
SHARAD Confidence: ${confidence} (${Math.round((data.confidence_score ?? 0.6) * 100)}%)
Ice Depth Estimate: ${data.ice_depth_formatted || `${iceDepth} m ± ${iceStd} m`}
Orbital Radar Passes: ${data.sharad_passes ?? 3}
Coverage Gap: ${data.coverage_gap_note || 'N/A'}
Geology: ${data.geology_note || 'N/A'}

Metrics:
- Ice Score: ${metrics.ice_score}
- Safety Score: ${metrics.safety_score} (Slope: ${metrics.slope_deg}°, Elevation: ${metrics.elevation_m}m)
- Power Score: ${metrics.power_score}
- Radiation Score: ${metrics.radiation_score}
Generated by AREOSITE Mars Base Suitability Engine`;

    try {
      navigator.clipboard.writeText(reportText);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      // Ignored
    }
  };

  return (
    <div className="hud-panel rounded-lg p-4 text-slate-200 tactical-corners">
      {/* Top Header */}
      <div className="flex items-start justify-between pb-3 mb-3 border-b border-slate-800">
        <div>
          <div className="flex items-center space-x-2">
            <span className="w-2 h-2 rounded-full bg-mars-red-bright animate-ping"></span>
            <h3 className="font-display font-bold text-base tracking-wide text-white">
              {data.site_name || 'Martian Region'}
            </h3>
          </div>
          <div className="flex items-center space-x-2 mt-0.5 text-xs font-mono text-slate-400">
            <Compass className="w-3.5 h-3.5 text-sky-400" />
            <span>{data.coordinates_formatted || `${data.lat?.toFixed(1) ?? 0}°, ${data.lon_180?.toFixed(1) ?? 0}°`}</span>
            <span>•</span>
            <span>{metrics.elevation_m} m Elevation</span>
          </div>
        </div>

        {/* Confidence Badge */}
        <div className="flex flex-col items-end">
          <span
            className={`px-2.5 py-1 rounded text-[11px] font-mono font-bold border ${badgeClass}`}
          >
            {confidence} CONFIDENCE
          </span>
          <span className="text-[10px] font-mono text-slate-400 mt-1">
            {data.sharad_passes ?? 3} SHARAD passes
          </span>
        </div>
      </div>

      {/* Main Score Hero Card */}
      <div className="grid grid-cols-2 gap-3 mb-4">
        {/* Suitability Score Callout */}
        <div className="bg-slate-900/90 border border-slate-800 rounded p-3 flex flex-col justify-center items-center relative overflow-hidden">
          <div className="text-[10px] font-mono text-slate-400 uppercase tracking-wider mb-1">
            Suitability Score
          </div>
          <div className="flex items-baseline space-x-1">
            <span className="font-display font-bold text-3xl text-emerald-400 tracking-tight">
              {scorePct}
            </span>
            <span className="text-emerald-500 font-mono text-sm">/ 100</span>
          </div>
          <div className="w-full bg-slate-800 h-1.5 rounded-full mt-2 overflow-hidden">
            <div
              className="bg-emerald-400 h-full rounded-full transition-all duration-300"
              style={{ width: `${Math.min(100, Math.max(0, scorePct))}%` }}
            ></div>
          </div>
        </div>

        {/* Ice Depth with Uncertainty Callout */}
        <div className="bg-slate-900/90 border border-slate-800 rounded p-3 flex flex-col justify-center items-center relative overflow-hidden">
          <div className="text-[10px] font-mono text-slate-400 uppercase tracking-wider mb-1 flex items-center gap-1">
            <Droplets className="w-3 h-3 text-sky-400" />
            <span>Ice Depth (ISRU)</span>
          </div>
          <div className="font-display font-bold text-lg text-sky-300 text-center tracking-tight">
            {data.ice_depth_formatted || `${iceDepth} m ± ${iceStd} m`}
          </div>
          <div className="text-[10px] font-mono text-slate-400 mt-1 flex items-center gap-1">
            <span>Sounder margin: ±{iceStd}m</span>
          </div>
        </div>
      </div>

      {/* Subsurface Stratum Radar Cross-Section Diagram */}
      <div className="mb-4 bg-slate-950/80 border border-slate-800 rounded p-3 font-mono text-xs">
        <div className="flex items-center justify-between text-[11px] text-slate-400 mb-2">
          <span className="flex items-center gap-1.5">
            <Waves className="w-3.5 h-3.5 text-sky-400" />
            <span className="text-slate-300 font-semibold">RADAR SOUNDER PROFILE</span>
          </span>
          <span className="text-[10px] text-slate-400">SHARAD 20 MHz ECHO</span>
        </div>

        <div className="border border-slate-800 rounded overflow-hidden">
          <div className="bg-[#6B2F1D]/80 px-2 py-1 flex items-center justify-between border-b border-[#8C3A24] text-[10px]">
            <span className="text-orange-200">0.0m Surface Regolith / Dust Mantle</span>
            <span className="text-orange-300/80">Dielectric ε ≈ 3.0</span>
          </div>

          <div 
            className="bg-[#0284c7]/35 px-2 py-2 flex items-center justify-between border-b border-[#38bdf8]/40 text-[10px]"
            style={{ minHeight: `${Math.max(28, Math.min(60, (iceDepth || 2) * 6))}px` }}
          >
            <div className="flex items-center space-x-1.5">
              <span className="w-2 h-2 rounded-full bg-sky-400 animate-pulse"></span>
              <span className="text-sky-200 font-semibold">
                Excess Water-Ice Layer (~{iceDepth}m depth)
              </span>
            </div>
            <span className="text-sky-300 font-mono text-[9px] bg-sky-950/80 px-1.5 py-0.5 rounded border border-sky-800">
              ±{iceStd}m error bar
            </span>
          </div>

          <div className="bg-slate-900 px-2 py-1.5 flex items-center justify-between text-[10px]">
            <span className="text-slate-400">Basaltic Bedrock Substrate</span>
            <span className="text-slate-500">Reflective Boundary</span>
          </div>
        </div>
      </div>

      {/* Criteria Breakdown Grid */}
      <div className="space-y-2 mb-4 font-mono text-xs">
        <div className="text-[11px] text-slate-400 font-semibold flex items-center gap-1">
          <Info className="w-3.5 h-3.5 text-mars-red-bright" />
          <span>CRITERIA SUB-SCORES</span>
        </div>

        <div className="grid grid-cols-2 gap-2 text-[11px]">
          <div className="p-2 rounded bg-slate-900/60 border border-slate-800/80 flex items-center justify-between">
            <span className="text-slate-400 flex items-center gap-1">
              <Droplets className="w-3 h-3 text-sky-400" /> Ice Score:
            </span>
            <span className="font-bold text-sky-400">{typeof metrics.ice_score === 'number' ? metrics.ice_score.toFixed(2) : '0.85'}</span>
          </div>

          <div className="p-2 rounded bg-slate-900/60 border border-slate-800/80 flex items-center justify-between">
            <span className="text-slate-400 flex items-center gap-1">
              <Mountain className="w-3 h-3 text-emerald-400" /> Slope:
            </span>
            <span className="font-bold text-emerald-400">{metrics.slope_deg ?? 1.2}°</span>
          </div>

          <div className="p-2 rounded bg-slate-900/60 border border-slate-800/80 flex items-center justify-between">
            <span className="text-slate-400 flex items-center gap-1">
              <Sun className="w-3 h-3 text-amber-400" /> Solar Insolation:
            </span>
            <span className="font-bold text-amber-400">{typeof metrics.power_score === 'number' ? metrics.power_score.toFixed(2) : '0.80'}</span>
          </div>

          <div className="p-2 rounded bg-slate-900/60 border border-slate-800/80 flex items-center justify-between">
            <span className="text-slate-400 flex items-center gap-1">
              <Radio className="w-3 h-3 text-purple-400" /> Column Shield:
            </span>
            <span className="font-bold text-purple-400">{typeof metrics.radiation_score === 'number' ? metrics.radiation_score.toFixed(2) : '0.80'}</span>
          </div>
        </div>
      </div>

      {/* Geologic and Coverage Notes */}
      <div className="p-3 rounded bg-slate-900/80 border border-slate-800 mb-4 font-mono text-xs space-y-1.5">
        <div>
          <span className="text-slate-400 font-semibold block text-[10px] uppercase">
            Radar Coverage Gap Analysis:
          </span>
          <p className="text-amber-300/90 text-[11px]">{data.coverage_gap_note || 'Regional orbital sounder survey active.'}</p>
        </div>
        <div>
          <span className="text-slate-400 font-semibold block text-[10px] uppercase">
            Geological Context:
          </span>
          <p className="text-slate-300 text-[11px] leading-relaxed">{data.geology_note || 'Martian surface terrain.'}</p>
        </div>
      </div>

      {/* Action Buttons */}
      <div className="flex items-center space-x-2 pt-2 border-t border-slate-800">
        <button
          onClick={() => onFlyToSite(data.lat ?? 35.0, data.lon_180 ?? -150.0)}
          className="flex-1 flex items-center justify-center space-x-1.5 px-3 py-2 rounded bg-mars-red hover:bg-mars-red-bright text-white font-mono text-xs font-semibold shadow-hud-red transition"
        >
          <Send className="w-3.5 h-3.5" />
          <span>FLY TO SITE</span>
        </button>

        <button
          onClick={handleExport}
          className="flex items-center space-x-1 px-3 py-2 rounded bg-slate-900 hover:bg-slate-800 text-slate-300 hover:text-white font-mono text-xs border border-slate-700 transition"
          title="Export report card summary to clipboard"
        >
          {copied ? (
            <>
              <Check className="w-3.5 h-3.5 text-emerald-400" />
              <span>COPIED</span>
            </>
          ) : (
            <>
              <Download className="w-3.5 h-3.5" />
              <span>EXPORT</span>
            </>
          )}
        </button>
      </div>
    </div>
  );
};
